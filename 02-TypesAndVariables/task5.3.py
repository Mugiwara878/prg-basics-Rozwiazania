a = input("type a: ")
b = input("type b: ")
c = input("type c: ")
a = int(a)
b = int(b)
c = int(c)
volume = a * b * c
surface_area = 2 * (a*b + b*c + a*c)
print(f"Volume of a cuboid with sides {a}, {b}, and {c} is :{volume}")
print(f"Surface area of a cuboid with sides {a}, {b}, and {c} is :{surface_area}")