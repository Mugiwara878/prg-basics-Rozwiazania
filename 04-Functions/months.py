def month(n):
    name_month = ''
    if n == 1:
        name_month = "January"
    elif n == 2:
        name_month = "February"
    elif n == 3:
        name_month = "March"
    elif n == 4:
        name_month = "April"
    elif n == 5:
        name_month = "May"
    elif n == 6:
        name_month = "June"
    elif n == 7:
        name_month = "July"
    elif n == 8:
        name_month = "August"
    elif n == 9:
        name_month = "September"
    elif n == 10:
        name_month = "October"
    elif n == 11:
        name_month = "November"
    elif n == 12:
        name_month = "December"
    else:
        name_month = "Wrong number"
    return name_month